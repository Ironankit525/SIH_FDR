"""Markdown report. Misses and false alarms are listed by name so weaknesses are not hidden in averages."""
from app import risk
from .corpus import GENUINE_KINDS, PROBLEM_KINDS

GENUINE_NOTES = {
    "genuine": "Clean bank-generated receipt",
    "genuine_scanned": "Genuine receipt, printed and scanned (OCR path, no text layer)",
    "genuine_joint_holding": "Held jointly with AICTE's Member Secretary",
    "genuine_bank_abbreviation": "Institution typed the bank's abbreviation (e.g. SBI)",
    "genuine_coverage_gap": "Short FDR for a longer obligation; renewal needed later",
}


def pct(value):
    return "—" if value is None else f"{value * 100:.0f}%"


def markdown(payload):
    m = payload["metrics"]
    t = m["thresholds"]
    stages = m["stages"]
    after = stages["after_bank_check"]
    lines = [
        "# Risk engine evaluation",
        "",
        f"Generated {payload['generated_on']} with risk engine {risk.ENGINE_VERSION} and the built-in weight policy. "
        f"Corpus: {m['cases']} synthetic cases ({m['problem_cases']} needing intervention, {m['genuine_cases']} genuine), seed {payload['corpus']['seed']}.",
        "",
        "> **Read this first.** Every institution, bank record and document here is fictional and generated by "
        "`backend/evaluation/corpus.py`. These numbers measure the engine against the problems it was designed for; "
        "they are not real-world fraud detection accuracy. Real forgeries will include techniques not modelled here. "
        "The score orders review work and never decides a case.",
        "",
        "## Headline",
        "",
        f"Medium is a score of {t['medium']} or more; high is {t['high']} or more.",
        "",
        "| Stage | AUC | Problem cases ≥ medium | Problem cases ≥ high | Genuine cases ≥ medium | Genuine cases ≥ high | Problem cases in top 10 |",
        "|---|---|---|---|---|---|---|",
    ]
    for stage, label in (("intake", "At intake (documents and declarations only)"), ("after_bank_check", "After the simulated bank check")):
        s = stages[stage]
        lines.append(f"| {label} | {s['auc']} | {pct(s['recall_at_medium'])} | {pct(s['recall_at_high'])} | "
                     f"{pct(s['false_positive_rate_at_medium'])} | {pct(s['false_positive_rate_at_high'])} | {pct(s['precision_at_10'])} |")
    lines += ["", "AUC is the chance that a randomly chosen problem case scores above a randomly chosen genuine one (0.5 is guessing, 1.0 is perfect separation).",
              "", "## By kind of case", "",
              "| Kind | What it represents | Cases | ≥ medium at intake | ≥ medium after bank check | ≥ high after bank check | Median score after bank check |",
              "|---|---|---|---|---|---|---|"]
    for kind in list(PROBLEM_KINDS) + list(GENUINE_KINDS):
        if kind not in after["per_kind"]:
            continue
        a, i = after["per_kind"][kind], stages["intake"]["per_kind"][kind]
        lines.append(f"| `{kind}` | {PROBLEM_KINDS.get(kind) or GENUINE_NOTES[kind]} | {a['cases']} | {pct(i['at_least_medium'])} | "
                     f"{pct(a['at_least_medium'])} | {pct(a['at_least_high'])} | {a['median_score']:.0f} |")
    lines += ["", "For genuine kinds, lower is better: the columns are false alarms.", "", "## Which signals fired (after the bank check)", "",
              "| Signal | Problem cases | Genuine cases | Precision |", "|---|---|---|---|"]
    for key, d in after["detectors"].items():
        lines.append(f"| `{key}` | {d['problem_cases']} | {d['genuine_cases']} | {pct(d['precision'])} |")
    cases = payload["cases"]
    missed = [c for c in cases if c["label"] and c["stages"]["after_bank_check"]["score"] < t["medium"]]
    alarms = [c for c in cases if not c["label"] and c["stages"]["after_bank_check"]["score"] >= t["medium"]]
    for title, rows in (("Problem cases still below medium after the bank check", missed), ("Genuine cases at medium or above after the bank check", alarms)):
        lines += ["", f"## {title}", ""]
        if not rows:
            lines.append("None.")
            continue
        lines += ["| Case | Kind | Score | Signals |", "|---|---|---|---|"]
        lines += [f"| {c['id']} | `{c['kind']}` | {c['stages']['after_bank_check']['score']:.0f} | {', '.join(c['stages']['after_bank_check']['signals']) or '—'} |" for c in rows]
    lines += ["", "## What this evaluation changed", "",
              "The first run (same engine version, earlier corpus with problem cases spread evenly over all institutions) flagged most genuine cases. "
              "Four engine flaws were fixed as general rules, then the same corpus was re-run before the corpus itself was changed:", "",
              "1. Bank names are compared with the normalisation duplicate detection already used (\"SBI\" = \"State Bank of India\").",
              "2. Institution history is capped below the medium threshold, so it adds weight to direct evidence but never raises a clean case alone.",
              "3. Reuse and duplicate signals point only at the later submission; the original holder is not the suspect.",
              "4. References compared against OCR readings fold look-alike characters (I/1, O/0, S/5, B/8), and a mismatch counts in proportion to the parser's confidence.",
              "", "| Earlier corpus | AUC at intake | Genuine ≥ medium at intake | AUC after bank check | Genuine ≥ medium after bank check | Problem ≥ medium after bank check |",
              "|---|---|---|---|---|---|",
              "| Before the fixes | 0.868 | 23% | 0.877 | 62% | 100% |",
              "| After the fixes | 0.943 | 0% | 1.0 | 5% | 100% |", "",
              "The corpus was then changed so problems cluster in about 30% of institutions, as they would in practice; the tables above use that corpus.",
              "", "### Receipt arithmetic check", "",
              "A forger who raises the principal or extends the term usually leaves the printed maturity value unchanged. The check accepts any common bank "
              "convention (simple interest; annual, half-yearly, quarterly or monthly compounding) within 1%, or, with no printed rate, an implied rate of 1–15% a year.",
              "", "| At intake | Clean rebuilt receipts ≥ medium | All problem cases ≥ medium | AUC |", "|---|---|---|---|",
              "| Before the check (seed 7) | 0% | 80% | 0.946 |",
              "| With the check (seed 7) | 100% | 90% | 0.989 |",
              "| With the check (seed 21) | 83% | 88% | 0.964 |", "",
              "The check can only fire when a receipt prints its maturity value; one of the corpus's three layouts does not, so expect roughly two-thirds "
              "coverage of clean rebuilds rather than the seed-7 figure. Its first run also exposed a corpus bug: genuine coverage-gap receipts printed a "
              "maturity value for the wrong term. The generator was fixed; the engine was not changed to accommodate it.",
              "", "## Limits of this evaluation", "",
              "- The same team wrote the detectors and the corpus, so the corpus contains the problems the detectors were built for. Treat high scores here as a regression baseline, not an accuracy claim.",
              "- Documents use three receipt layouts with clean typography. Real bank receipts, stamps, handwriting, skewed photographs and regional languages are not represented.",
              "- Fabricated receipts that are internally consistent leave no trace in the document, and clean rebuilds whose receipts omit the maturity value pass the arithmetic check; only bank confirmation exposes them. Without a live bank channel those cases depend on officers obtaining confirmation.",
              "- The bank check is simulated against the corpus's own records.",
              ]
    lines += ["", "## Method", "",
              "Each case goes through the real API: the institution creates the deposit, uploads the receipt and submits; "
              "the score is read (intake). A verification officer then runs the simulated bank check against what the bank actually holds, "
              "every case is rescored once all exist (as the daily sweep would), and the score is read again. "
              "A submission refused as a duplicate counts as detected with score 100.",
              "", "Reproduce from `backend/`: `../.venv/bin/python -m evaluation`. "
              "The regression gate (`tests/test_risk_evaluation.py`) runs a smaller corpus and fails if detection falls below `evaluation/baseline.json`.", ""]
    return "\n".join(lines)
